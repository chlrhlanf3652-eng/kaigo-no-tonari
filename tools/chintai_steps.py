# -*- coding: utf-8 -*-
"""COVERS の ◎○△× から、その区で取るべき順番を組み立てる。

区の制度が埋めてくれる欄は「区の窓口でまとめて済ませる」、
埋まらない欄は「自分で先に用意する」——この振り分けが区ごとに変わるので、
同じ3ステップでも中身と順番が区によって違う文章になる。
"""

SCORE = {"◎": 3, "○": 2, "△": 1, "×": 0}


def _li(text):
    return "      <li>%s</li>" % text


def steps(ward, madoguchi, cov):
    """貸主の3つの不安を、埋まっている順ではなく『先に手を打つべき順』に並べる。"""
    out = []
    rank = {k: SCORE[cov[k][0]] for k in ("家賃", "安否", "退去")}

    # 1. 家賃 — 審査で最初に見られるので必ず先頭
    if rank["家賃"] >= 3:
        out.append(_li("<strong>区の助成を先に申請する。</strong>%s。"
                       "申請が通っていれば、申し込みの時点で「保証は区の制度で手当て済み」と伝えられます。"
                       % cov["家賃"][1]))
    elif rank["家賃"] == 2:
        out.append(_li("<strong>区が関わる物件・制度から当たる。</strong>%s。"
                       "民間物件を回る前にこちらの空きを確認してください。" % cov["家賃"][1]))
    else:
        out.append(_li("<strong>家賃債務保証会社を自分で決めてから物件を探す。</strong>%s。"
                       "高齢者住宅財団の家賃債務保証のように高齢者世帯を想定した制度を先に押さえておけば、"
                       "%sで内見まで進んだあとに保証会社が見つからず流れる事態を防げます。"
                       % (cov["家賃"][1], ward)))

    # 2. 安否 — 貸主が二番目に気にする点
    if rank["安否"] >= 3:
        out.append(_li("<strong>区の安否確認を同時に申し込む。</strong>%s。"
                       "入居申込書に見守りの有無を書ける状態にしてから不動産店へ行きます。"
                       % cov["安否"][1]))
    elif rank["安否"] == 2:
        out.append(_li("<strong>窓口に相談するとき、入居後の見守りまで一緒に頼む。</strong>%s。"
                       "物件探しと見守りを別々に進めると、契約直前に貸主から求められて慌てます。"
                       % cov["安否"][1]))
    else:
        out.append(_li("<strong>見守りサービスを先に契約しておく。</strong>%s。"
                       "民間の安否確認か%sの緊急通報システムを申し込み前に押さえておくと、"
                       "貸主への説明材料になります。" % (cov["安否"][1], ward)))

    # 3. 退去 — 断り文句として最後に出てくる
    if rank["退去"] >= 3:
        out.append(_li("<strong>残置物の取り決めを区の制度で済ませる。</strong>%s。"
                       "ここが決まっていると、貸主が最後に持ち出す不安がなくなります。" % cov["退去"][1]))
    else:
        out.append(_li("<strong>残置物の引き取りと解約について、家族の同意書を用意する。</strong>%s。"
                       "%sでは国土交通省のモデル契約条項にならって「解除・残置物処理の受任者」を"
                       "先に決めておくと、貸主が最後に持ち出す不安に答えられます。"
                       % (cov["退去"][1], ward)))

    # 4. 窓口 — ここまでそろえてから相談に行く
    out.append(_li("<strong>%sへ相談する。</strong>"
                   "①〜③をそろえてから行くと、紹介できる物件の幅が変わります。" % madoguchi))
    return "\n".join(out)


def lead(ward, madoguchi, cov):
    """その区が3つの不安をどこまで埋めているかを、最初の段落で言い切る。"""
    n = sum(1 for k in ("家賃", "安否", "退去") if SCORE[cov[k][0]] >= 2)
    gaps = [k for k in ("家賃", "安否", "退去") if SCORE[cov[k][0]] <= 1]
    LABEL = {"家賃": "家賃を払い続けられるか", "安否": "室内で事故が起きないか",
             "退去": "退去時の対応ができるか"}
    head = ("年齢を理由に断られるのは、年齢そのものではなく"
            "<strong>家賃・安否・退去の3つの不安</strong>が理由です。")
    if n == 3:
        tail = ("%sはこの3つすべてに区の制度が用意されている区です。"
                "<strong>%s</strong>で手続きをまとめれば、貸主に示す材料がそろいます。" % (ward, madoguchi))
    elif n == 0:
        tail = ("%sの場合、この3つを区の制度で埋めることはできません。"
                "<strong>%s</strong>は物件と情報の入口として使い、"
                "%sは自分で先に用意しておくのが近道です。"
                % (ward, madoguchi, "・".join(LABEL[g] for g in gaps[:2])))
    else:
        tail = ("%sで区の制度が届くのはこのうち%d つで、%sは自分で用意することになります。"
                "まず<strong>%s</strong>で埋まる部分を確認してください。"
                % (ward, n, "・".join(LABEL[g] for g in gaps), madoguchi))
    return head + tail


def close(ward, cov):
    n = sum(1 for k in ("家賃", "安否", "退去") if SCORE[cov[k][0]] >= 2)
    if n >= 2:
        return ("区の制度で貸主の不安をかなり埋められる%sでも、"
                "物件そのものの数が少なければ決まりません。"
                "条件のうち駅からの距離と築年数は先に緩めておくと、候補が一気に増えます。" % ward)
    return ("%sは区の制度で埋まる部分が限られるぶん、"
            "保証会社・見守り・残置物の3点を自分でそろえた人から決まっていきます。"
            "この3点が用意できている旨を先に伝えると、同じ物件でも回答が変わることがあります。" % ward)
